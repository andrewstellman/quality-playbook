"""v1.5.7 instruction 089n (#183 "B-9") — setup_repos.sh bundle
parity guard.

`repos/setup_repos.sh` builds each benchmark target's installed
skill by hand-copying files. Its copy list has historically
drifted from `bin/install_skill.py::_bundle_files()` — the
canonical source of truth for what a real adopter install ships —
in both directions:

  - **Over-bundle**: setup_repos.sh used to copy
    `ai_context/AI_ORCHESTRATION_PATTERNS.md`, the QPB-root
    `AGENTS.md`, and `LICENSE.txt` to the target. install_skill.py
    ships none of those, so the benchmark target carried artifacts
    a real adopter would never have pre-placed. The AGENTS.md case
    was internally inconsistent: the clean-source path copied it,
    while the from-prior fallback path deleted it with the comment
    "Generated by the skill, not part of source." 089n removes
    all three.

  - **Under-bundle**: setup_repos.sh omitted `bin/run_state_lib.py`,
    `bin/validate_phase_artifacts.py`, and `bin/qpb_config.py` —
    the A-26 trio (instruction 086). install_skill.py ships them
    via the loop at `bin/install_skill.py:220-227`. The benchmark
    only got away with the gap because targets sit under the QPB
    clone and resolve `python3 -m bin.X` against the clone's bin/
    (the lax-sandbox masking effect 086 documents). 089n adds the
    three cp lines so the benchmark bundle matches the adopter
    bundle.

This test is the parity guard. It parses
`repos/setup_repos.sh` (the bash source, NOT executing it — fast,
filesystem-free, fixture-free) and compares the set of `bin/*.py`
basenames it copies AND the set of target-root files it copies
against `bin/install_skill.py::_bundle_files()`. The guard fires
if either lane re-adds an over-bundle or drops an A-26 module.

The instruction explicitly says NOT to un-skip the W5/082 slow
filesystem-touching `test_setup_repos.py` body — this is a
separate, fast, parse-only sibling.

**Mutation-bite evidence**:

- *Re-add the AGENTS.md cp* (e.g.,
  `cp "${QPB_DIR}/AGENTS.md" "${dst}/AGENTS.md"` somewhere) →
  `test_setup_repos_does_not_copy_adopter_parity_overbundles`
  fails with the AGENTS.md needle present.
- *Remove an A-26 trio cp* (e.g., delete the
  `bin/qpb_config.py` line) →
  `test_setup_repos_copies_a26_trio` fails listing the missing
  module.

Both bites executed PASS → FAIL → PASS during 089n development.

The fuller single-source `_bundle_files()` refactor (making
setup_repos.sh derive its file list by calling _bundle_files()
so the lanes can never drift again) is tracked by the in-code
TODOs at `setup_repos.sh:229-232` and `:268-271`; it stays a
separate v1.5.7.x consolidation. 089n only edits the hand-copy
list; this guard pins the current state.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

from bin import install_skill


REPO_ROOT = Path(__file__).resolve().parent.parent.parent
SETUP_REPOS_SH = REPO_ROOT / "repos" / "setup_repos.sh"


def _parse_setup_repos_cp_destinations() -> list[str]:
    """Parse `repos/setup_repos.sh` and return the list of literal
    cp destination paths (the *target-relative* path each cp
    writes to). We extract from any line matching
    ``cp ... "${dst}/<rel-path>"`` — that's setup_repos.sh's
    consistent target-write idiom. Lines without ``${dst}`` are
    ignored (those are reads from ${QPB_DIR} or ${SCRIPT_DIR}
    only; we want the destination side)."""
    text = SETUP_REPOS_SH.read_text(encoding="utf-8")
    pattern = re.compile(
        r'^\s*cp\s+[^\n]*?"\$\{dst\}/([^"]+)"',
        re.MULTILINE,
    )
    return pattern.findall(text)


def _parse_setup_repos_bin_basenames() -> set[str]:
    """Subset of cp destinations under ``bin/``. Returns just the
    basename (e.g. ``run_state_lib.py``)."""
    out: set[str] = set()
    for dest in _parse_setup_repos_cp_destinations():
        # dest is target-relative, e.g. "bin/run_state_lib.py" or
        # ".github/skills/SKILL.md".
        if dest.startswith("bin/"):
            tail = dest[len("bin/"):]
            # Only direct children — no subdir entries.
            if "/" not in tail:
                out.add(tail)
    return out


def _install_skill_bin_basenames() -> set[str]:
    """Return the set of `bin/*.py`-style basenames
    `_bundle_files()` ships under the target's bin/ directory."""
    out: set[str] = set()
    for _src, dest in install_skill._bundle_files(REPO_ROOT):
        parts = dest.parts
        # We want direct children of bin/ — no subdir entries.
        if len(parts) == 2 and parts[0] == "bin":
            out.add(parts[1])
    return out


class SetupReposBundleParity089nTests(unittest.TestCase):
    """Pin the current parity state between setup_repos.sh's
    hand-copy list and install_skill.py::_bundle_files(). Each
    test names exactly what would have to change to flip it,
    serving as a drift guard."""

    def test_setup_repos_copies_a26_trio(self) -> None:
        """Positive pin (under-bundle direction): setup_repos.sh
        MUST copy the three A-26 modules to the target's bin/,
        matching install_skill.py::_bundle_files()."""
        bin_basenames = _parse_setup_repos_bin_basenames()
        for trio_member in (
            "run_state_lib.py",
            "validate_phase_artifacts.py",
            "qpb_config.py",
        ):
            self.assertIn(
                trio_member, bin_basenames,
                f"089n parity guard: setup_repos.sh must copy "
                f"bin/{trio_member} to the target. "
                f"install_skill.py::_bundle_files() ships it at "
                f"bin/install_skill.py:220-227. The benchmark "
                f"bundle must match the adopter bundle.",
            )

    def test_setup_repos_does_not_copy_adopter_parity_overbundles(self) -> None:
        """Negative pin (over-bundle direction): setup_repos.sh
        MUST NOT copy the QPB-root AGENTS.md, the
        AI_ORCHESTRATION_PATTERNS.md, or LICENSE.txt to the
        target. install_skill.py::_bundle_files() ships none of
        them; their presence at the target contaminates the
        benchmark."""
        destinations = set(_parse_setup_repos_cp_destinations())
        forbidden = {
            # The contamination is at target-root (AGENTS.md is
            # generated by the playbook itself at B-17).
            "AGENTS.md",
            # The patterns doc was under target's ai_context/.
            "ai_context/AI_ORCHESTRATION_PATTERNS.md",
            # LICENSE was under target's .github/skills/.
            ".github/skills/LICENSE.txt",
        }
        for needle in forbidden:
            self.assertNotIn(
                needle, destinations,
                f"089n parity guard: setup_repos.sh must NOT copy "
                f"{needle} to the target — install_skill.py does "
                f"not ship it, so pre-placing it via the benchmark "
                f"lane creates adopter-parity drift. (AGENTS.md "
                f"specifically must be generated by the playbook "
                f"itself per the B-17 generation flow.)",
            )

    def test_install_skill_does_not_bundle_overbundle_set(self) -> None:
        """Sanity pin: the over-bundle set 089n removed is in fact
        NOT in install_skill.py's bundle. This catches a future
        accidental addition to _bundle_files() that would flip
        the parity claim from the install_skill.py side."""
        dest_paths = {str(dest) for _src, dest in install_skill._bundle_files(REPO_ROOT)}
        for forbidden in (
            "AGENTS.md",
            "ai_context/AI_ORCHESTRATION_PATTERNS.md",
            "LICENSE.txt",
            ".github/skills/LICENSE.txt",
        ):
            self.assertNotIn(
                forbidden, dest_paths,
                f"089n parity guard: install_skill.py::_bundle_files() "
                f"must not bundle {forbidden}. If this changed, "
                f"setup_repos.sh's over-bundle removal needs to "
                f"be re-evaluated against the new parity baseline.",
            )

    def test_setup_repos_bin_set_is_superset_of_install_skill_bin_set(self) -> None:
        """Positive sanity pin: setup_repos.sh's bin/ copy set
        must be a SUPERSET of install_skill.py's. setup_repos.sh
        may legitimately copy MORE than _bundle_files() (the
        benchmark-only extras like ``install_skill.py`` itself,
        kept per the harness's Mode-A install-step need), but
        it must not be MISSING anything install_skill.py ships.

        This is the load-bearing parity assertion: any future
        addition to _bundle_files() that setup_repos.sh forgets
        to mirror trips this test."""
        sr_bin = _parse_setup_repos_bin_basenames()
        ip_bin = _install_skill_bin_basenames()
        missing = ip_bin - sr_bin
        self.assertEqual(
            missing, set(),
            f"089n parity guard: setup_repos.sh is missing "
            f"{sorted(missing)} from its bin/ cp list. "
            f"install_skill.py::_bundle_files() ships these to "
            f"the target's bin/; the benchmark bundle must "
            f"match. Add the corresponding `cp \"${{QPB_DIR}}/"
            f"bin/<name>\" \"${{dst}}/bin/<name>\" ...` line in "
            f"setup_repos.sh.",
        )


if __name__ == "__main__":
    unittest.main()
