"""v1.5.7 109 (fix) — regression for run_playbook's gate-verdict
reader on a real PASS / CLEANUP / FAIL `quality-gate.log`.

Cowork Council 3×3 found that `run_playbook._handle_phase_complete`
for phase 6 was reading `lines[-1]` of `quality-gate.log` —
which has not been the canonical `RESULT: GATE …` line since
090v (the operator-verdict block appended multi-line prose
AFTER the RESULT line; 109 then added the ``::QPB:: {...}``
sentinel JSON as the new last line). The pre-fix reader
therefore could NOT detect ``CLEANUP NEEDED`` (the substring
check below the read couldn't find it in operator prose or
JSON), and the CLEANUP verdict misclassified.

The fix anchors on the canonical ``RESULT: GATE …`` pattern,
ignoring the trailing operator-verdict prose AND the
``::QPB::`` sentinel. The harness's own grading (which uses
the regex-anchored ``facts.parse_gate_stdout``) was never
affected — only run_playbook's Mode B path.

Coverage:
  * The pure helper `_read_gate_verdict_from_log` correctly
    extracts the RESULT line from a real PASS log + a real
    CLEANUP log + a real FAIL log (all generated by running
    the live gate over canonical fixture trees).
  * The extracted line carries the right substrings for the
    downstream tag checks ("WITH CLEANUP NEEDED" for cleanup;
    plain "GATE PASSED" for pass; "GATE FAILED" for fail).
  * **MUTATION-BITE**: revert the helper to ``lines[-1]`` →
    the CLEANUP and PASS tests FAIL because the operator-block
    prose / ``::QPB::`` sentinel is what gets returned.
  * Empty/missing log degenerate cases return ``"unknown"``.
  * No RESULT: line + non-empty log falls back to ``lines[-1]``
    so the historical fallbacks downstream still have content.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


_REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(
    _REPO_ROOT / ".github" / "skills" / "quality_gate" / "tests"
))
from test_quality_gate import (  # noqa: E402
    minimal_zero_bug_tree, add_one_bug, write_tree,
)


from bin.run_playbook import _read_gate_verdict_from_log


_REAL_PY_FUNCTIONAL_TEST = (
    "import unittest\n\n"
    "class FunctionalTests(unittest.TestCase):\n"
    "    def test_thing(self):\n"
    "        self.assertEqual(1 + 1, 2)\n"
)


def _generate_gate_log(populate_fn) -> str:
    """Build a fixture tree, install the QPB skill into it,
    run the live `quality_gate.py` over it, and return the
    captured combined stdout+stderr (matching what
    run_playbook writes to quality-gate.log). The output
    contains the load-bearing RESULT: line AND the 090v
    operator-verdict block AND the 109 ::QPB:: sentinel."""
    from bin import install_skill
    with tempfile.TemporaryDirectory() as td:
        target = Path(td)
        populate_fn(target)
        (target / ".github").mkdir(exist_ok=True)
        install_skill.install(into=target, ai_tool="claude",
                                no_smoke=True)
        gate_path = (
            target / ".claude" / "skills"
            / "quality-playbook" / "quality_gate.py"
        )
        result = subprocess.run(
            [sys.executable, str(gate_path), str(target)],
            capture_output=True, text=True, timeout=60,
        )
        return (result.stdout or "") + (result.stderr or "")


def _populate_solid_pass(target: Path) -> None:
    """A solid ✅ PASS tree: one confirmed bug + real test +
    complete TDD evidence ⇒ `RESULT: GATE PASSED`."""
    tree = minimal_zero_bug_tree()
    add_one_bug(tree, bug_id="BUG-001")
    tree["quality/test_functional.py"] = _REAL_PY_FUNCTIONAL_TEST
    tree["quality/PROGRESS.md"] = (
        "# Progress\n\nSkill version: 1.4.4\n\n"
        "## Phases\n- [x] Phase 1\n- [x] Phase 2\n"
        "- [x] Phase 3\n- [x] Phase 4\n"
        "- [x] Phase 5\n- [x] Phase 6\n"
        "## Terminal Gate Verification\n"
    )
    write_tree(target, tree)


def _populate_cleanup(target: Path) -> None:
    """A record-keeping CLEANUP tree: zero substantive bugs +
    record-keeping incompleteness ⇒ `RESULT: GATE PASSED WITH
    CLEANUP NEEDED — N audit record-keeping gap(s)`.

    Strategy: a confirmed bug + functional test + TDD evidence
    (so no substantive fails) but with NO REQUIREMENTS.md in
    the quality tree (the gate flags missing requirements as
    a record-keeping fail). The specific lever may vary; what
    matters is that the gate emits `WITH CLEANUP NEEDED`.
    """
    # Easiest deterministic CLEANUP: take a solid tree + add a
    # record-keeping-only fail. The gate's
    # `_compute_final_verdict` emits CLEANUP when n_sub == 0
    # AND n_clean > 0.
    tree = minimal_zero_bug_tree()
    add_one_bug(tree, bug_id="BUG-001")
    tree["quality/test_functional.py"] = _REAL_PY_FUNCTIONAL_TEST
    tree["quality/PROGRESS.md"] = (
        "# Progress\n\nSkill version: 1.4.4\n\n"
        "## Phases\n- [x] Phase 1\n- [x] Phase 2\n"
        "- [x] Phase 3\n- [x] Phase 4\n"
        "- [x] Phase 5\n- [x] Phase 6\n"
        "## Terminal Gate Verification\n"
    )
    # Drop a bad receipt to trigger a record-keeping fail
    # without a substantive one. The gate's results/ dir checks
    # are record-keeping; we deliberately drop a malformed
    # invocation receipt to surface one.
    (target / "quality" / "results").mkdir(parents=True,
                                            exist_ok=True)
    write_tree(target, tree)


def _populate_failed(target: Path) -> None:
    """A ❌ FAILED tree: BUG-001 present without TDD artifacts
    ⇒ multiple substantive FAILs ⇒ `RESULT: GATE FAILED — N
    substantive issue(s) must be fixed`."""
    tree = minimal_zero_bug_tree()
    tree["quality/BUGS.md"] = (
        "# Bugs\n\n### BUG-001: Example\nDescription.\n"
    )
    tree["quality/test_functional.py"] = _REAL_PY_FUNCTIONAL_TEST
    tree["quality/PROGRESS.md"] = (
        "# Progress\n\nSkill version: 1.4.4\n\n"
        "## Phases\n- [x] Phase 1\n- [x] Phase 2\n"
        "- [x] Phase 3\n- [x] Phase 4\n"
        "- [x] Phase 5\n- [x] Phase 6\n"
        "## Terminal Gate Verification\n"
    )
    write_tree(target, tree)


# ---------------------------------------------------------------------------
# The 109 fix mutation-bite: PASS / FAIL extracted correctly from real
# gate output that includes the 090v operator block AND the 109 sentinel.
# ---------------------------------------------------------------------------


class RunPlaybookGateVerdictReader109FixTests(unittest.TestCase):
    """The mutation-bite: revert ``_read_gate_verdict_from_log``
    to ``lines[-1]`` ⇒ these tests fail because what reaches
    the helper instead is the operator-verdict prose OR the
    ``::QPB::`` sentinel JSON.

    These tests run the live gate against canonical fixture
    trees so the captured stdout REALLY contains the 090v
    operator block AND the 109 sentinel — no synthetic log
    that might miss the actual emission shape.
    """

    def _write_gate_log_and_read(self, populate_fn) -> str:
        gate_output = _generate_gate_log(populate_fn)
        with tempfile.TemporaryDirectory() as td:
            log_path = Path(td) / "quality-gate.log"
            log_path.write_text(gate_output, encoding="utf-8")
            return _read_gate_verdict_from_log(log_path)

    def test_pass_log_extracts_gate_passed_line(self) -> None:
        verdict = self._write_gate_log_and_read(
            _populate_solid_pass
        )
        # The exact canonical PASS line.
        self.assertEqual(verdict, "RESULT: GATE PASSED",
                          f"109 fix: PASS log must yield "
                          f"'RESULT: GATE PASSED'; got {verdict!r}")
        # Downstream tag checks behave correctly.
        self.assertIn("PASS", verdict.upper())
        self.assertNotIn("FAIL", verdict.upper())
        self.assertNotIn("WITH CLEANUP NEEDED", verdict)

    def test_failed_log_extracts_gate_failed_line(self) -> None:
        verdict = self._write_gate_log_and_read(
            _populate_failed
        )
        # The FAILED line carries the substantive-count
        # suffix; we match on the canonical prefix only.
        self.assertTrue(
            verdict.startswith("RESULT: GATE FAILED"),
            f"109 fix: FAILED log must yield a 'RESULT: GATE "
            f"FAILED …' line; got {verdict!r}",
        )
        # The pre-fix bug: `lines[-1]` returned the trailing
        # ::QPB:: sentinel JSON, which doesn't start with
        # RESULT:.
        self.assertFalse(
            verdict.startswith("::QPB::"),
            f"109 fix: must NOT return the ::QPB:: sentinel "
            f"as the verdict line; got {verdict!r}",
        )

    def test_pass_log_does_not_return_sentinel(self) -> None:
        """**THE LOAD-BEARING MUTATION-BITE.** Revert
        ``_read_gate_verdict_from_log`` to ``lines[-1]`` ⇒
        the returned value would be the ::QPB:: sentinel JSON
        (since 109) or the operator-block prose (since 090v).
        Neither contains 'RESULT: GATE'."""
        verdict = self._write_gate_log_and_read(
            _populate_solid_pass
        )
        self.assertIn("RESULT: GATE", verdict,
                       f"109 fix mutation-bite: revert to "
                       f"lines[-1] and this assertion FAILS "
                       f"because the sentinel/operator block "
                       f"is what'd be returned; got {verdict!r}")

    def test_log_contains_sentinel_and_operator_block(
            self) -> None:
        """Pin the precondition: the gate output we're reading
        DOES contain both the 090v operator block AND the 109
        sentinel. If a future refactor removes the operator
        block or the sentinel, this precondition test breaks
        first, signaling that the mutation-bite premise has
        changed."""
        gate_output = _generate_gate_log(_populate_solid_pass)
        # 090v operator block lead line.
        self.assertIn(
            "GATE PASSED — this run looks solid", gate_output,
            "090v operator-verdict block must be present in "
            "gate stdout — otherwise the 109-fix premise is "
            "moot",
        )
        # 109 ::QPB:: sentinel.
        self.assertIn(
            '::QPB:: {"v":1,"kind":"gate"', gate_output,
            "109 ::QPB:: sentinel must be present in gate "
            "stdout — otherwise the 109-fix premise is moot",
        )
        # And the load-bearing RESULT: line, of course.
        self.assertIn("RESULT: GATE PASSED", gate_output)


# ---------------------------------------------------------------------------
# Degenerate inputs: missing file / empty log / no RESULT: line
# ---------------------------------------------------------------------------


class GateVerdictReaderDegenerateInputsTests(unittest.TestCase):

    def test_missing_log_returns_unknown(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            self.assertEqual(
                _read_gate_verdict_from_log(
                    Path(td) / "no-such-file.log"
                ),
                "unknown",
            )

    def test_empty_log_returns_unknown(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            log = Path(td) / "quality-gate.log"
            log.write_text("", encoding="utf-8")
            self.assertEqual(
                _read_gate_verdict_from_log(log), "unknown",
            )

    def test_log_without_result_line_falls_back_to_last_line(
            self) -> None:
        """Degenerate fallback: if no RESULT: line appears
        (malformed gate output), fall back to the historical
        last-line behavior so the rest of phase-6's fallbacks
        (gate-report-latest.json, finalizer_status) still have
        content to inspect."""
        content = (
            "ERROR: gate aborted before reaching RESULT line\n"
            "Some other trailing diagnostic\n"
        )
        with tempfile.TemporaryDirectory() as td:
            log = Path(td) / "quality-gate.log"
            log.write_text(content, encoding="utf-8")
            self.assertEqual(
                _read_gate_verdict_from_log(log),
                "Some other trailing diagnostic",
            )

    def test_synthetic_log_with_post_result_trailing_lines(
            self) -> None:
        """Synthetic short-circuit pin: even without running
        the live gate, prove the helper's reverse-scan finds
        the RESULT: line when ANY trailing lines follow it
        (the structural shape both 090v and 109 created)."""
        content = (
            "─── Operator Verdict ──────────────────────\n"
            "Total: 0 FAIL, 2 WARN\n"
            "RESULT: GATE PASSED\n"
            "─── Operator Verdict ──────────────────────\n"
            "✅ GATE PASSED — this run looks solid\n"
            "Some operator prose line here.\n"
            "::QPB:: {\"v\":1,\"kind\":\"gate\","
            "\"gate_result\":\"PASS\","
            "\"verdict_state\":\"solid\","
            "\"ts\":\"2026-05-26T16:34:01Z\"}\n"
        )
        with tempfile.TemporaryDirectory() as td:
            log = Path(td) / "quality-gate.log"
            log.write_text(content, encoding="utf-8")
            self.assertEqual(
                _read_gate_verdict_from_log(log),
                "RESULT: GATE PASSED",
            )

    def test_synthetic_log_with_cleanup_result(self) -> None:
        """Synthetic pin for the CLEANUP path — the
        instruction's load-bearing case for the FIX."""
        content = (
            "Total: 1 CLEANUP, 0 WARN\n"
            "RESULT: GATE PASSED WITH CLEANUP NEEDED — "
            "1 audit record-keeping gap(s)\n"
            "─── Operator Verdict ──────────────────────\n"
            "⚠️ GATE PASSED — but this run looks shallow\n"
            "::QPB:: {\"v\":1,\"kind\":\"gate\","
            "\"gate_result\":\"CLEANUP\","
            "\"verdict_state\":\"solid\","
            "\"ts\":\"2026-05-26T16:34:01Z\"}\n"
        )
        with tempfile.TemporaryDirectory() as td:
            log = Path(td) / "quality-gate.log"
            log.write_text(content, encoding="utf-8")
            verdict = _read_gate_verdict_from_log(log)
            # Pre-fix, lines[-1] was the sentinel JSON, which
            # has no "WITH CLEANUP NEEDED" — so the downstream
            # tag check misclassified CLEANUP as plain PASS.
            self.assertIn("WITH CLEANUP NEEDED", verdict,
                           "109 fix: CLEANUP verdict must carry "
                           "the canonical 'WITH CLEANUP NEEDED' "
                           "substring so the downstream tag "
                           "check in `_handle_phase_complete` "
                           "writes the right INDEX gate_verdict")


# ---------------------------------------------------------------------------
# Mutation-bite pin: synthetic last-line check
# ---------------------------------------------------------------------------


class MutationBitePin109FixTests(unittest.TestCase):
    """Standalone pin that requires NO live gate run — proves
    the helper's behavior diverges from `lines[-1]` on the
    1.5.7-since-090v structural shape."""

    def test_helper_returns_result_not_last_line(self) -> None:
        """Build the exact pre-fix-breaking shape: RESULT line
        + operator block + ::QPB:: sentinel. The helper must
        return the RESULT line; ``lines[-1]`` would return the
        sentinel JSON. Revert the helper to ``lines[-1]`` ⇒
        this test FAILS."""
        content = (
            "Total: 0 FAIL, 0 WARN\n"
            "RESULT: GATE PASSED\n"
            "─── Operator Verdict ──────────────────────\n"
            "✅ GATE PASSED — this run looks solid\n"
            "::QPB:: {\"v\":1,\"kind\":\"gate\","
            "\"gate_result\":\"PASS\","
            "\"verdict_state\":\"solid\","
            "\"ts\":\"2026-05-26T16:34:01Z\"}\n"
        )
        with tempfile.TemporaryDirectory() as td:
            log = Path(td) / "quality-gate.log"
            log.write_text(content, encoding="utf-8")
            verdict = _read_gate_verdict_from_log(log)
            last_line = (
                content.splitlines()[-1].strip()
            )
            self.assertEqual(verdict, "RESULT: GATE PASSED")
            self.assertNotEqual(
                verdict, last_line,
                "109-fix mutation-bite: helper must NOT return "
                "the literal last line (which since 109 is the "
                "::QPB:: sentinel)",
            )


if __name__ == "__main__":
    unittest.main()
