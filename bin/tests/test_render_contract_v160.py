"""v1.6.0 Feature C — REQUIREMENTS.md render-contract checks.

Pins the six mechanical checks from ``QPB_v1.6.0_Design.md`` §5.3 plus the
F-1 advisory coverage-and-gaps check, all implemented by
``quality_gate.check_render_contract``.

Every check here is **mutation-bitten**: each ``test_*_fires`` re-introduces
exactly one defect class into an otherwise-conforming document and asserts
the gate FAILs with a message naming the defect. A check that cannot fail is
not a check, so each firing test is paired with the clean-document baseline
in :class:`RenderContractCleanDocumentTests`.

The defect classes are the seven observed in the 2026-06-19 chi / express /
virtio benchmark runs and enumerated in the design doc as C-1..C-7:

    C-1  tool-process contamination      -> test_c1_*
    C-2  scrambled identifiers           -> test_c2_*
    C-3  degenerate singleton sections   -> test_c3_*
    C-4  narrative inconsistency         -> test_c4_*
    C-5  derivation internals in render  -> test_c5_*
    C-6  bug-shaped requirements         -> test_c6_*
    C-7  stale generator stamp           -> test_c7_*

AUDIT table
-----------
``RENDER_CONTRACT_AUDIT`` below enumerates every defect class the contract
covers together with the check that pins it. A new render-contract check
must add a row; the size guard at the bottom of
:class:`RenderContractAuditSweepTests` fails until it does.
"""

