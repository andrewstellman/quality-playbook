"""v1.6.0 — no hardcoded skill-version literals in agent-copied templates.

Defect class (C-7): a reference doc or phase prompt shows the agent a
template containing a concrete version number. The agent copies the literal.
The artifact ships stamped with a version that has nothing to do with the
run that produced it.

Observed instances:

- ``references/phase2_generation_guide.md`` carried ``v1.5.3`` in the
  mandatory Markdown attribution stamp, ten lines above a rule saying the
  stamp must match SKILL.md ``metadata.version``. The 2026-06-19 chi run
  copied the literal and stamped ``v1.5.3`` on a v1.5.8 run; express and
  virtio followed the rule and stamped correctly. Same skill, same day,
  same pipeline — the divergence is the tell.
- The same file's code-file stamp template carried ``v1.5.7``, and a worked
  example diff carried ``v1.5.7``.
- ``references/artifact_contract.md`` (x3), ``references/recheck_mode.md``,
  and ``references/phase1_exploration_guide.md`` carried
  ``"skill_version": "1.5.x"`` in sidecar-JSON templates. The last one sits
  inside an executable heredoc the agent is told to run as its first action,
  and the ``artifact_contract.md`` ones feed
  ``quality_gate.check_version_stamps``, which FAILs on a mismatch — so a
  copied literal there is a gate failure, not cosmetic drift.

This is a third-firing defect class, so it earns an AUDIT-table sweep per
``ai_context/DEVELOPMENT_PROCESS.md`` § "AUDIT-table invariant test pattern"
rather than another point fix.

AUDIT table
-----------
``ALLOWED_VERSION_LITERAL_CONTEXTS`` below lists every place a concrete
version string may legitimately appear in the swept surface, with the reason.
A new literal must either use the ``<SKILL_VERSION>`` placeholder or earn an
explicit, justified row here.
"""

import re
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
REFERENCES = REPO_ROOT / "references"
PHASE_PROMPTS = (
    REPO_ROOT / "plugins" / "quality-playbook" / "skills" / "quality-playbook"
    / "phase_prompts"
)

# The placeholder every template must use instead of a literal.
PLACEHOLDER = "<SKILL_VERSION>"

# Fields whose value the agent copies verbatim into a generated artifact.
# These are the load-bearing ones — a wrong value here reaches the adopter.
_STAMPED_FIELD_RE = re.compile(
    r'"(?:skill_version|schema_version)":\s*"(\d+\.\d+(?:\.\d+)?)"'
)

# A "Generated by Quality Playbook vX.Y.Z" attribution stamp template.
_STAMP_TEMPLATE_RE = re.compile(
    r"Generated by[^\n]*?Quality Playbook[^\n]*?\bv(\d+\.\d+(?:\.\d+)?)"
)

# AUDIT table — (relative_path, matched_text_fragment, justification).
#
# Every entry is a version literal that is NOT an agent-copied template and
# is therefore allowed to stay concrete.
ALLOWED_VERSION_LITERAL_CONTEXTS = [
    (
        "artifact_contract.md",
        '"schema_version": "1.1"',
        "Sidecar schema version, not the skill version. It is a genuine "
        "constant of the sidecar format and does not track releases.",
    ),
    (
        "artifact_contract.md",
        '"schema_version": "1.0"',
        "Run-metadata schema version — same reasoning as above.",
    ),
    (
        "recheck_mode.md",
        '"schema_version": "1.0"',
        "Recheck sidecar schema version, not the skill version.",
    ),
    (
        "phase1_exploration_guide.md",
        '"schema_version": "1.0"',
        "Run-metadata schema version, not the skill version.",
    ),
    (
        "phase_prompts/phase3.md",
        '"schema_version": "1.5.2" (compensation_grid.json)',
        "Format version of the compensation-grid artifact, which happens to "
        "be named for the release that introduced the format. NOT a skill "
        "version: it is stable at 1.5.2 across the 2026-06-19 chi, express "
        "and virtio runs (all executed under v1.5.8), and no gate check "
        "compares it against the detected skill version. Surfaced by this "
        "sweep during instruction 001 and dispositioned as allowed.",
    ),
    (
        "phase_prompts/phase3.md",
        '"schema_version": "1.5.2" (compensation_grid_downgrades.json)',
        "Same artifact family, same reasoning as the row above.",
    ),
]

# Schema/format versions that are genuine constants of an artifact format
# rather than a copy of the skill version. See the AUDIT rows above.
_ALLOWED_SCHEMA_VALUES = {"1.0", "1.1", "1.5.2"}


def _swept_files():
    files = sorted(REFERENCES.glob("*.md"))
    files += sorted(PHASE_PROMPTS.glob("*.md"))
    return files


class SkillVersionLiteralSweepTests(unittest.TestCase):
    """No agent-copied template may carry a concrete skill version."""

    def test_no_hardcoded_skill_version_in_json_templates(self):
        offenders = []
        for path in _swept_files():
            text = path.read_text(encoding="utf-8", errors="replace")
            for m in _STAMPED_FIELD_RE.finditer(text):
                field = m.group(0).split('"')[1]
                value = m.group(1)
                if field == "schema_version" and value in _ALLOWED_SCHEMA_VALUES:
                    continue
                line_no = text[: m.start()].count("\n") + 1
                offenders.append(
                    f"{path.relative_to(REPO_ROOT)}:{line_no}: {m.group(0)}"
                )
        self.assertEqual(
            offenders, [],
            "Hardcoded skill-version literal(s) in agent-copied JSON "
            f"templates. Use {PLACEHOLDER} and tell the agent to substitute "
            "SKILL.md metadata.version:\n  " + "\n  ".join(offenders),
        )

    def test_no_hardcoded_version_in_attribution_stamp_templates(self):
        offenders = []
        for path in _swept_files():
            text = path.read_text(encoding="utf-8", errors="replace")
            for m in _STAMP_TEMPLATE_RE.finditer(text):
                line_no = text[: m.start()].count("\n") + 1
                offenders.append(
                    f"{path.relative_to(REPO_ROOT)}:{line_no}: {m.group(0)!r}"
                )
        self.assertEqual(
            offenders, [],
            "Hardcoded version literal(s) in a 'Generated by Quality "
            f"Playbook v...' stamp template. Use {PLACEHOLDER}. This is the "
            "exact defect that made the 2026-06-19 chi run stamp v1.5.3 on "
            "a v1.5.8 run:\n  " + "\n  ".join(offenders),
        )

    def test_placeholder_is_actually_used_somewhere(self):
        """Guard against the sweep passing because the templates vanished."""
        hits = [
            path.relative_to(REPO_ROOT)
            for path in _swept_files()
            if PLACEHOLDER in path.read_text(encoding="utf-8", errors="replace")
        ]
        self.assertGreaterEqual(
            len(hits), 4,
            "Expected the <SKILL_VERSION> placeholder in several templates. "
            "If it is missing, the sweep above is passing vacuously — the "
            f"templates were deleted rather than parameterized. Found: {hits}",
        )

    def test_generation_guide_tells_the_agent_to_substitute(self):
        """A placeholder with no substitution instruction is just a new bug."""
        text = (REFERENCES / "phase2_generation_guide.md").read_text(
            encoding="utf-8", errors="replace"
        )
        self.assertIn(PLACEHOLDER, text)
        self.assertIn("placeholder, not a literal", text)
        self.assertIn("metadata.version", text)

    def test_audit_table_size_matches_known_allowed_contexts(self):
        self.assertEqual(
            len(ALLOWED_VERSION_LITERAL_CONTEXTS), 6,
            "AUDIT table size changed. Every concrete version literal left "
            "in the swept surface needs a justified row. If you added a "
            "legitimate one, add its row and update this expected size.",
        )


if __name__ == "__main__":
    unittest.main()
